using Shared.FacilityDomain.Abstractions.ValueObjects;

namespace Shared.FacilityDomain.Abstractions.Propagation;

/// <summary>A stage in a hazard propagation chain -- either an originating hazard or a downstream consequence.</summary>
public enum PropagationStage
{
    /// <summary>An uncontrolled fire (originating hazard).</summary>
    Fire,

    /// <summary>Smoke generated by a fire.</summary>
    Smoke,

    /// <summary>Personnel evacuation triggered by smoke or another life-safety consequence.</summary>
    Evacuation,

    /// <summary>A chemical spill (originating hazard).</summary>
    Spill,

    /// <summary>A vapor cloud generated by a spill.</summary>
    Vapor,

    /// <summary>Personnel exposure to a vapor cloud or other airborne hazard.</summary>
    Exposure,

    /// <summary>A machine/equipment failure (originating hazard).</summary>
    MachineFailure,

    /// <summary>An injury resulting from a machine failure or exposure.</summary>
    Injury,

    /// <summary>An operational shutdown triggered by injury or another severe consequence.</summary>
    Shutdown,
}

/// <summary>Raised for one step of a hazard propagation chain within a facility.</summary>
public sealed record HazardPropagationEvent(
    FacilityId FacilityId,
    PropagationStage FromStage,
    PropagationStage ToStage,
    DateTime OccurredAtUtc);
