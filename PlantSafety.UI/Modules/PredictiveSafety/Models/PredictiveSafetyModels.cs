using System;
using System.Collections.Generic;

namespace PlantSafety.UI.Modules.PredictiveSafety.Models;

/// <summary>Represents a single predictive safety model output / risk prediction (mirrors <c>PredictiveSafetyItemDto</c>).</summary>
public sealed class PredictiveSafetyItemDto
{
    /// <summary>Gets the unique identifier of the predictive safety output record.</summary>
    public Guid PredictionId { get; init; }

    /// <summary>Gets the tenant identifier.</summary>
    public Guid TenantId { get; init; }

    /// <summary>Gets the site identifier, or null when not site-scoped.</summary>
    public Guid? SiteId { get; init; }

    /// <summary>Gets the category of risk predicted (e.g., Fatigue, Fall, Equipment).</summary>
    public string RiskCategory { get; init; } = string.Empty;

    /// <summary>Gets the predicted risk score (0.0-1.0) generated by the model.</summary>
    public double PredictedRiskScore { get; init; }

    /// <summary>Gets the version identifier of the predictive model that generated this output.</summary>
    public string? ModelVersion { get; init; }

    /// <summary>Gets the current alert status (e.g., Active/Acknowledged/Resolved).</summary>
    public string Status { get; init; } = string.Empty;

    /// <summary>Gets the UTC timestamp when the prediction was generated.</summary>
    public DateTime PredictedAtUtc { get; init; }

    /// <summary>Gets the identity of the model/process that generated the prediction.</summary>
    public Guid GeneratedBy { get; init; }
}

/// <summary>Envelope returned by GET v1/intelligence/predictivesafety (mirrors <c>PredictiveSafetyResponse</c>).</summary>
public sealed class PredictiveSafetyResponseDto
{
    /// <summary>Gets the tenant the data belongs to.</summary>
    public Guid TenantId { get; init; }

    /// <summary>Gets the site the data is scoped to, or null for tenant-wide results.</summary>
    public Guid? SiteId { get; init; }

    /// <summary>Gets the UTC timestamp when this read-model snapshot was generated.</summary>
    public DateTime GeneratedAt { get; init; }

    /// <summary>Gets the prediction items in the requested window.</summary>
    public IReadOnlyList<PredictiveSafetyItemDto> Items { get; init; } = [];
}
