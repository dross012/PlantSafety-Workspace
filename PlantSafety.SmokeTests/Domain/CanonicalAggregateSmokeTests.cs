using PlantSafety.Domain.Operational.Alerts.Aggregates;
using PlantSafety.Domain.Operational.Alerts.Enums;
using PlantSafety.Domain.Common.Types.StrongIds;
using PlantSafety.SharedKernel.Identifiers;
using PlantSafety.SharedKernel.Primitives.ValueTypes;

namespace PlantSafety.SmokeTests.Domain;

public sealed class CanonicalAggregateSmokeTests
{
    private static readonly UserId Actor = UserId.FromGuid(Guid.NewGuid());
    private static readonly CorrelationId Correlation = new(Guid.NewGuid());
    private static readonly CausationId Causation = new(Guid.NewGuid());

    [Fact(DisplayName = "PLNT-SMKE-DOM-001: Alert.Create succeeds for every AlertType x AlertSeverity combination")]
    public void AlertCreate_ShouldSucceed_ForAllTypeSeverityCombinations()
    {
        foreach (var type in AlertType.All)
        {
            foreach (var severity in AlertSeverity.All)
            {
                var act = () => Alert.Create(
                    type,
                    severity,
                    "Smoke test alert",
                    "Generated by PLNT-SMKE-DOM-001",
                    "SmokeTests",
                    Actor,
                    UtcTimestamp.Now(),
                    Correlation,
                    Causation,
                    PerformedByActor.User(Actor));

                act.Should().NotThrow();
            }
        }
    }

    [Fact(DisplayName = "PLNT-SMKE-DOM-002: A newly created Alert starts in a non-terminal status")]
    public void NewAlert_ShouldStartInNonTerminalStatus()
    {
        var alert = Alert.Create(
            AlertType.WorkerSafety,
            AlertSeverity.Critical,
            "Worker safety alarm",
            "Smoke created alert",
            "SmokeTests",
            Actor,
            UtcTimestamp.Now(),
            Correlation,
            Causation,
            PerformedByActor.User(Actor));

        alert.Status.Should().NotBeNull();
        alert.AlertId.Should().NotBeNull();
    }

    [Fact(DisplayName = "PLNT-FUNC-ALARM-001: Alert.Create rejects a blank title (fail-safe input validation)")]
    public void AlertCreate_WithBlankTitle_ShouldThrow()
    {
        var act = () => Alert.Create(
            AlertType.WorkerSafety,
            AlertSeverity.Emergency,
            "   ",
            "description",
            "SmokeTests",
            Actor,
            UtcTimestamp.Now(),
            Correlation,
            Causation,
            PerformedByActor.User(Actor));

        act.Should().Throw<ArgumentException>();
    }
}
