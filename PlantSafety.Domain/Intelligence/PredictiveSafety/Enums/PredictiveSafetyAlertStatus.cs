namespace PlantSafety.Domain.Intelligence.PredictiveSafety.Enums;

/// <summary>Lifecycle states for a <see cref="Aggregates.PredictiveSafetyAlert"/> record.</summary>
public enum PredictiveSafetyAlertStatus
{
    /// <summary>The alert has been generated by the predictive model and requires review. Initial state on Create.</summary>
    Active = 0,

    /// <summary>A user has acknowledged the alert.</summary>
    Acknowledged = 1,

    /// <summary>The alert has been resolved.</summary>
    Resolved = 2,

    /// <summary>The alert has been archived for compliance retention.</summary>
    Archived = 3,
}
