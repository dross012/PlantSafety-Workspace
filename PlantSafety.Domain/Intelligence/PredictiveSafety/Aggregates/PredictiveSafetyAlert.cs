using PlantSafety.SharedKernel.Identifiers;
using PlantSafety.SharedKernel.Primitives.ValueTypes;
using PlantSafety.Domain.Intelligence.PredictiveSafety.Enums;
using PlantSafety.Domain.Intelligence.PredictiveSafety.Events;
using PlantSafety.Domain.Intelligence.PredictiveSafety.Exceptions;
using PlantSafety.Domain.Intelligence.PredictiveSafety.Rules;
using PlantSafety.Domain.Intelligence.PredictiveSafety.ValueObjects.Ids;

namespace PlantSafety.Domain.Intelligence.PredictiveSafety.Aggregates;

/// <summary>Aggregate root for the Intelligence.PredictiveSafety bounded context.</summary>
public sealed class PredictiveSafetyAlert
{
    // ---- Identity ------------------------------------------------------------

    /// <summary>Strong-typed identity of this PredictiveSafetyAlert aggregate.</summary>
    public PredictiveSafetyAlertId PredictiveSafetyAlertId { get; private set; }

    /// <summary>Tenant that owns this predictive safety alert record.</summary>
    public Guid TenantId { get; private set; }

    /// <summary>Site this record is scoped to. Null means enterprise-level.</summary>
    public Guid? SiteId { get; private set; }

    /// <summary>Current lifecycle status.</summary>
    public PredictiveSafetyAlertStatus Status { get; private set; }

    // ---- PredictiveSafetyAlert-specific business properties -----------------

    /// <summary>Category of risk predicted (e.g., Fatigue, Fall, Equipment).</summary>
    public string RiskCategory { get; private set; } = string.Empty;

    /// <summary>Predicted risk score generated by the model.</summary>
    public double PredictedRiskScore { get; private set; }

    /// <summary>Version identifier of the predictive model that generated this output.</summary>
    public string? ModelVersion { get; private set; }

    /// <summary>UTC timestamp when the prediction was generated.</summary>
    public UtcTimestamp PredictedAtUtc { get; private set; }

    /// <summary>Identity of the process/service that generated the prediction (domain action identity).</summary>
    public UserId GeneratedBy { get; private set; }

    // ---- Lifecycle attributes (Acknowledge/Resolve/Archive) -----------------

    /// <summary>Identity of the user who acknowledged the alert.</summary>
    public UserId? AcknowledgedBy { get; private set; }

    /// <summary>UTC instant the alert was acknowledged.</summary>
    public UtcTimestamp? AcknowledgedAtUtc { get; private set; }

    /// <summary>Identity of the user who resolved the alert.</summary>
    public UserId? ResolvedBy { get; private set; }

    /// <summary>Resolution notes recorded when the alert was resolved, if any.</summary>
    public string? ResolutionNotes { get; private set; }

    /// <summary>UTC instant the alert was resolved.</summary>
    public UtcTimestamp? ResolvedAtUtc { get; private set; }

    /// <summary>UTC instant the alert was archived for compliance retention.</summary>
    public UtcTimestamp? ArchivedAtUtc { get; private set; }

    /// <summary>UTC creation timestamp.</summary>
    public UtcTimestamp CreatedAtUtc { get; private set; }

    /// <summary>Identity of the user who created this record (CRUD authorship).</summary>
    public UserId CreatedBy { get; private set; }

    // ---- Domain Events ---------------------------------------------------------

    private readonly List<IPredictiveSafetyAlertDomainEvent> _domainEvents = [];

    /// <summary>Domain events raised during this unit of work.</summary>
    public IReadOnlyCollection<IPredictiveSafetyAlertDomainEvent> DomainEvents => _domainEvents.AsReadOnly();

    // For rehydration only.
    private PredictiveSafetyAlert() { }

    // ---- Factory ---------------------------------------------------------------

    /// <summary>
    /// Creates a new Intelligence.PredictiveSafety alert record and raises
    /// <see cref="PredictiveSafetyAlertCreatedEvent"/>.
    /// </summary>
    /// <exception cref="ArgumentException">A required field is missing or empty.</exception>
    public static PredictiveSafetyAlert Create(
        UserId createdBy,
        UtcTimestamp createdAtUtc,
        CorrelationId correlationId,
        CausationId causationId,
        PerformedByActor actor,
        Guid tenantId,
        Guid? siteId,
        string riskCategory,
        double predictedRiskScore,
        string? modelVersion,
        UserId generatedBy)
    {
        var normalizedRiskCategory = (riskCategory ?? string.Empty).Trim();
        var normalizedModelVersion = string.IsNullOrWhiteSpace(modelVersion) ? null : modelVersion.Trim();

        if (tenantId == Guid.Empty)
            throw new ArgumentException("TenantId is required.", nameof(tenantId));
        if (string.IsNullOrWhiteSpace(normalizedRiskCategory))
            throw new ArgumentException("RiskCategory is required.", nameof(riskCategory));
        if (generatedBy == default)
            throw new ArgumentException("GeneratedBy is required.", nameof(generatedBy));

        var agg = new PredictiveSafetyAlert
        {
            PredictiveSafetyAlertId = PredictiveSafetyAlertId.New(),
            TenantId = tenantId,
            SiteId = siteId,
            Status = PredictiveSafetyAlertStatus.Active,
            RiskCategory = normalizedRiskCategory,
            PredictedRiskScore = predictedRiskScore,
            ModelVersion = normalizedModelVersion,
            PredictedAtUtc = createdAtUtc,
            GeneratedBy = generatedBy,
            CreatedAtUtc = createdAtUtc,
            CreatedBy = createdBy,
        };

        agg.AddDomainEvent(new PredictiveSafetyAlertCreatedEvent(
            EventId: PredictiveSafetyAlertEventId.New(),
            PredictiveSafetyAlertId: agg.PredictiveSafetyAlertId,
            TenantId: tenantId,
            SiteId: siteId,
            RiskCategory: agg.RiskCategory,
            PredictedRiskScore: agg.PredictedRiskScore,
            ModelVersion: agg.ModelVersion,
            GeneratedBy: generatedBy,
            PredictedAtUtc: createdAtUtc,
            Actor: actor,
            CorrelationId: correlationId,
            CausationId: causationId));

        return agg;
    }

    // ---- Lifecycle: Acknowledge -----------------------------------------------

    /// <summary>
    /// Acknowledges the alert (Active -&gt; Acknowledged). Valid only from
    /// <see cref="PredictiveSafetyAlertStatus.Active"/>.
    /// </summary>
    public void Acknowledge(
        UserId acknowledgedBy,
        UtcTimestamp acknowledgedAtUtc,
        PerformedByActor actor,
        CorrelationId correlationId,
        CausationId causationId)
    {
        EnsureStatusIsOneOf(correlationId, causationId, PredictiveSafetyAlertLifecycleRules.CanAcknowledge, PredictiveSafetyAlertStatus.Acknowledged);

        AcknowledgedBy = acknowledgedBy;
        AcknowledgedAtUtc = acknowledgedAtUtc;
        Status = PredictiveSafetyAlertStatus.Acknowledged;

        AddDomainEvent(new PredictiveSafetyAlertAcknowledgedEvent(
            EventId: PredictiveSafetyAlertEventId.New(),
            PredictiveSafetyAlertId: PredictiveSafetyAlertId,
            AcknowledgedBy: acknowledgedBy,
            AcknowledgedAtUtc: acknowledgedAtUtc,
            Actor: actor,
            CorrelationId: correlationId,
            CausationId: causationId));
    }

    // ---- Lifecycle: Resolve -----------------------------------------------------

    /// <summary>
    /// Resolves the alert (Acknowledged -&gt; Resolved). Valid only from
    /// <see cref="PredictiveSafetyAlertStatus.Acknowledged"/>.
    /// </summary>
    public void Resolve(
        UserId resolvedBy,
        string? resolutionNotes,
        UtcTimestamp resolvedAtUtc,
        PerformedByActor actor,
        CorrelationId correlationId,
        CausationId causationId)
    {
        EnsureStatusIsOneOf(correlationId, causationId, PredictiveSafetyAlertLifecycleRules.CanResolve, PredictiveSafetyAlertStatus.Resolved);

        ResolvedBy = resolvedBy;
        ResolutionNotes = string.IsNullOrWhiteSpace(resolutionNotes) ? null : resolutionNotes.Trim();
        ResolvedAtUtc = resolvedAtUtc;
        Status = PredictiveSafetyAlertStatus.Resolved;

        AddDomainEvent(new PredictiveSafetyAlertResolvedEvent(
            EventId: PredictiveSafetyAlertEventId.New(),
            PredictiveSafetyAlertId: PredictiveSafetyAlertId,
            ResolvedBy: resolvedBy,
            ResolutionNotes: ResolutionNotes,
            ResolvedAtUtc: resolvedAtUtc,
            Actor: actor,
            CorrelationId: correlationId,
            CausationId: causationId));
    }

    // ---- Lifecycle: Archive ---------------------------------------------------------

    /// <summary>
    /// Archives a resolved alert for compliance retention (Resolved -&gt; Archived). Valid only
    /// from <see cref="PredictiveSafetyAlertStatus.Resolved"/>.
    /// </summary>
    public void Archive(
        UtcTimestamp archivedAtUtc,
        PerformedByActor actor,
        CorrelationId correlationId,
        CausationId causationId)
    {
        EnsureStatusIsOneOf(correlationId, causationId, PredictiveSafetyAlertLifecycleRules.CanArchive, PredictiveSafetyAlertStatus.Archived);

        ArchivedAtUtc = archivedAtUtc;
        Status = PredictiveSafetyAlertStatus.Archived;

        AddDomainEvent(new PredictiveSafetyAlertArchivedEvent(
            EventId: PredictiveSafetyAlertEventId.New(),
            PredictiveSafetyAlertId: PredictiveSafetyAlertId,
            ArchivedAtUtc: archivedAtUtc,
            Actor: actor,
            CorrelationId: correlationId,
            CausationId: causationId));
    }

    // ---- Helpers -----------------------------------------------------------

    private void AddDomainEvent(IPredictiveSafetyAlertDomainEvent evt) => _domainEvents.Add(evt);

    /// <summary>Clears the in-memory event list after dispatch.</summary>
    public void ClearDomainEvents() => _domainEvents.Clear();

    private void EnsureStatusIsOneOf(CorrelationId correlationId, CausationId causationId, Func<PredictiveSafetyAlertStatus, bool> guard, PredictiveSafetyAlertStatus expected)
    {
        if (guard(Status)) return;

        throw new PredictiveSafetyAlertInvalidStatusTransitionException(PredictiveSafetyAlertId, Status.ToString(), expected.ToString(), correlationId, causationId);
    }
}
