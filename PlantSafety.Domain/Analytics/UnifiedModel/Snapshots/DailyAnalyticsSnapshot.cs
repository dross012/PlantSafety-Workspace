using PlantSafety.SharedKernel.Primitives.ValueTypes;
using PlantSafety.Domain.Analytics.UnifiedModel.ValueObjects.Ids;

namespace PlantSafety.Domain.Analytics.UnifiedModel.Snapshots;

/// <summary>
/// Immutable, append-only daily rollup snapshot of unified-model KPIs for a single
/// tenant/site/domain/business-date combination. Snapshots are never updated or deleted;
/// corrections are made by appending a new snapshot with a later <see cref="GeneratedAtUtc"/>.
/// </summary>
public sealed record DailyAnalyticsSnapshot
{
    /// <summary>Surrogate key of this snapshot row.</summary>
    public required UnifiedFactId SnapshotId { get; init; }

    /// <summary>Tenant this snapshot belongs to.</summary>
    public required Guid TenantId { get; init; }

    /// <summary>Site this snapshot is scoped to, or null for a tenant-wide rollup.</summary>
    public Guid? SiteKey { get; init; }

    /// <summary>Business date this snapshot summarizes.</summary>
    public required DateOnly BusinessDate { get; init; }

    /// <summary>Source domain summarized by this row (Scheduling, Operational, Maintenance, RiskManagement, ContinuousImprovement, Auditing).</summary>
    public required string Domain { get; init; }

    /// <summary>Total count of fact events contributing to this snapshot.</summary>
    public required long EventCount { get; init; }

    /// <summary>Count of events/items that were compliant/on-time/closed-on-time, as applicable to the domain.</summary>
    public required long CompliantCount { get; init; }

    /// <summary>Compliance/on-time rate for this domain on this date, expressed 0.0-1.0.</summary>
    public required double ComplianceRate { get; init; }

    /// <summary>Average cycle time in days for closable items in this domain (CAPA/RCA/audit findings), if applicable.</summary>
    public double? AverageCycleTimeDays { get; init; }

    /// <summary>Rolling 30-day trend direction relative to the prior snapshot: "Improving", "Stable", "Declining".</summary>
    public required string TrendDirection { get; init; }

    /// <summary>UTC instant this snapshot row was generated by the analytics rollup pipeline.</summary>
    public required UtcTimestamp GeneratedAtUtc { get; init; }

    /// <summary>Schema/algorithm version used to compute this snapshot's derived metrics.</summary>
    public required int ComputationVersion { get; init; }
}
