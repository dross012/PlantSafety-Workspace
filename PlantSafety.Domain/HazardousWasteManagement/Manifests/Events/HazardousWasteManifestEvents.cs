using PlantSafety.Domain.HazardousWasteManagement.Manifests.ValueObjects.Ids;

namespace PlantSafety.Domain.HazardousWasteManagement.Manifests.Events;

/// <summary>Raised when a manifest is generated by the generator.</summary>
public sealed record ManifestGeneratedEvent(
    HazardousWasteManifestEventId EventId,
    HazardousWasteManifestId HazardousWasteManifestId,
    string ManifestNumber,
    Guid WasteStreamId,
    UtcTimestamp OccurredAtUtc,
    PerformedByActor Actor,
    CorrelationId CorrelationId,
    CausationId CausationId
) : IHazardousWasteManifestDomainEvent
{
    /// <inheritdoc/>
    public string EventType => "ManifestGenerated";
    /// <inheritdoc/>
    public int EventVersion => 1;
    /// <inheritdoc/>
    public string SchemaVersion => "2026.2";
}

