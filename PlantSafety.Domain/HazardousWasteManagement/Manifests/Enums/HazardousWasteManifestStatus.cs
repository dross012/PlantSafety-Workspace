namespace PlantSafety.Domain.HazardousWasteManagement.Manifests.Enums;

/// <summary>Lifecycle states for the HazardousWasteManifest aggregate root.</summary>
public enum HazardousWasteManifestStatus
{
    /// <summary>Manifest generated by the generator, awaiting transporter pickup.</summary>
    Generated = 0,

    /// <summary>Transporter has signed and taken custody; manifest becomes immutable.</summary>
    InTransit = 1,

    /// <summary>TSDF facility has signed for receipt.</summary>
    ReceivedAtTsdf = 2,

    /// <summary>Manifest closed out with disposal certification.</summary>
    Closed = 3,

    /// <summary>A discrepancy (quantity, waste code, or signature mismatch) has been flagged.</summary>
    DiscrepancyFlagged = 4,
}
