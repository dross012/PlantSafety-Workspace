namespace PlantSafety.Application.Intelligence.PredictiveSafety.Models;

/// <summary>Represents a single predictive safety model output (risk prediction).</summary>
public sealed record PredictiveSafetyItemDto
{
    /// <summary>Unique identifier of the predictive safety output record.</summary>
    public required Guid PredictionId { get; init; }

    /// <summary>Tenant identifier.</summary>
    public required Guid TenantId { get; init; }

    /// <summary>Site identifier, or null when not site-scoped.</summary>
    public Guid? SiteId { get; init; }

    /// <summary>Category of risk predicted (e.g., Fatigue, Fall, Equipment).</summary>
    public required string RiskCategory { get; init; }
    /// <summary>Predicted risk score (0.0-1.0) generated by the model.</summary>
    public required double PredictedRiskScore { get; init; }
    /// <summary>Version identifier of the predictive model that generated this output.</summary>
    public string? ModelVersion { get; init; }

    /// <summary>Current alert status (e.g., Active/Acknowledged/Resolved).</summary>
    public required string Status { get; init; }

    /// <summary>UTC timestamp when the prediction was generated.</summary>
    public required DateTime PredictedAtUtc { get; init; }

    /// <summary>Identity of the model/process that generated the prediction.</summary>
    public required Guid GeneratedBy { get; init; }
}