namespace PlantSafety.Application.Intelligence.PredictiveSafety.Models;

/// <summary>A single PredictiveSafetyAlert read-model record, including the full lifecycle state.</summary>
public sealed record PredictiveSafetyAlertDetailDto
{
    /// <summary>Predictive safety alert identifier.</summary>
    public required Guid PredictiveSafetyAlertId { get; init; }

    /// <summary>Tenant identifier.</summary>
    public required Guid TenantId { get; init; }

    /// <summary>Site identifier, or null when not site-scoped.</summary>
    public Guid? SiteId { get; init; }

    /// <summary>Category of risk predicted (e.g., Fatigue, Fall, Equipment).</summary>
    public required string RiskCategory { get; init; }

    /// <summary>Predicted risk score generated by the model.</summary>
    public required double PredictedRiskScore { get; init; }

    /// <summary>Version identifier of the predictive model that generated this output.</summary>
    public string? ModelVersion { get; init; }

    /// <summary>Current lifecycle status (Active/Acknowledged/Resolved/Archived).</summary>
    public required string Status { get; init; }

    /// <summary>UTC timestamp when the prediction was generated.</summary>
    public required DateTime PredictedAtUtc { get; init; }

    /// <summary>Identity of the process/service that generated the prediction.</summary>
    public required Guid GeneratedBy { get; init; }

    /// <summary>Identity of the user who acknowledged the alert.</summary>
    public Guid? AcknowledgedBy { get; init; }

    /// <summary>UTC instant the alert was acknowledged.</summary>
    public DateTime? AcknowledgedAtUtc { get; init; }

    /// <summary>Identity of the user who resolved the alert.</summary>
    public Guid? ResolvedBy { get; init; }

    /// <summary>Resolution notes recorded when the alert was resolved, if any.</summary>
    public string? ResolutionNotes { get; init; }

    /// <summary>UTC instant the alert was resolved.</summary>
    public DateTime? ResolvedAtUtc { get; init; }

    /// <summary>UTC instant the alert was archived for compliance retention.</summary>
    public DateTime? ArchivedAtUtc { get; init; }

    /// <summary>UTC timestamp when the record was created.</summary>
    public required DateTime CreatedAtUtc { get; init; }

    /// <summary>Identity of the user who created this record.</summary>
    public required Guid CreatedBy { get; init; }

    /// <summary>
    /// Optimistic-concurrency token (native RowVersion projected as a hex string). Callers must
    /// echo this value back on a subsequent mutating command's ETag field; a stale/mismatched
    /// value results in a concurrency-conflict error.
    /// </summary>
    public string? ETag { get; init; }
}
