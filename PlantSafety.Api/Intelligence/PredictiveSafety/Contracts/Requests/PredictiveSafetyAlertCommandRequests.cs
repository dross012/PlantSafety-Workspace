namespace PlantSafety.Api.Intelligence.PredictiveSafety.Contracts.Requests;

/// <summary>Request body for creating a new Intelligence.PredictiveSafety alert record.</summary>
public sealed record CreatePredictiveSafetyAlertRequest
{
    /// <summary>Optional site scope. Null applies tenant-wide.</summary>
    public Guid? SiteId { get; init; }

    /// <summary>Category of risk predicted (e.g., Fatigue, Fall, Equipment).</summary>
    public required string RiskCategory { get; init; }

    /// <summary>Predicted risk score generated by the model.</summary>
    public required double PredictedRiskScore { get; init; }

    /// <summary>Version identifier of the predictive model that generated this output.</summary>
    public string? ModelVersion { get; init; }
}

/// <summary>Request body for acknowledging a predictive safety alert (Active -&gt; Acknowledged).</summary>
public sealed record AcknowledgePredictiveSafetyAlertRequest
{
    /// <summary>Optimistic-concurrency token from the last read of this alert record. Null skips the check.</summary>
    public string? ETag { get; init; }
}

/// <summary>Request body for resolving a predictive safety alert (Acknowledged -&gt; Resolved).</summary>
public sealed record ResolvePredictiveSafetyAlertRequest
{
    /// <summary>Resolution notes recorded at resolution time, if any.</summary>
    public string? ResolutionNotes { get; init; }

    /// <summary>Optimistic-concurrency token from the last read of this alert record. Null skips the check.</summary>
    public string? ETag { get; init; }
}

/// <summary>Request body for archiving a resolved predictive safety alert for compliance retention (Resolved -&gt; Archived).</summary>
public sealed record ArchivePredictiveSafetyAlertRequest
{
    /// <summary>Optimistic-concurrency token from the last read of this alert record. Null skips the check.</summary>
    public string? ETag { get; init; }
}
